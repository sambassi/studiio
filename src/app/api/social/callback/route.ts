async function exchangeMetaToken(code: string, platform: string) {
    const appId = platform === 'instagram'
      ? process.env.META_INSTAGRAM_APP_ID || process.env.FACEBOOK_CLIENT_ID
          : process.env.FACEBOOK_CLIENT_ID;
    const appSecret = platform === 'instagram'
      ? process.env.META_INSTAGRAM_APP_SECRET || process.env.FACEBOOK_CLIENT_SECRET
          : process.env.FACEBOOK_CLIENT_SECRET;
    const redirectUri = `${process.env.NEXTAUTH_URL || process.env.NEXT_PUBLIC_APP_URL}/api/social/callback?platform=${platform}`;

  // Exchange code for short-lived token
  const tokenRes = await fetch(
        `https://graph.facebook.com/v24.0/oauth/access_token?` +
        `client_id=${appId}&client_secret=${appSecret}&code=${code}&redirect_uri=${encodeURIComponent(redirectUri)}`
      );
    const tokenData = await tokenRes.json();

  if (tokenData.error) {
        throw new Error(tokenData.error.message);
  }

  // Exchange for long-lived token (60 days)
  const longTokenRes = await fetch(
        `https://graph.facebook.com/v24.0/oauth/access_token?` +
        `grant_type=fb_exchange_token&client_id=${appId}&client_secret=${appSecret}&fb_exchange_token=${tokenData.access_token}`
      );
    const longTokenData = await longTokenRes.json();
    let accessToken = longTokenData.access_token || tokenData.access_token;

  // Get account info
  let accountId = '';
    let accountName = '';

  if (platform === 'instagram') {
        // Get Instagram Business Account ID via Facebook Pages
        // User may have multiple pages — iterate all to find the one with an IG Business Account
      const pagesRes = await fetch(
              `https://graph.facebook.com/v24.0/me/accounts?fields=id,name,access_token,instagram_business_account&access_token=${accessToken}`
            );
        const pagesData = await pagesRes.json();
        const pages = pagesData.data || [];

        console.log(`[OAuth/Instagram] Found ${pages.length} Facebook Pages:`, pages.map((p: any) => ({ id: p.id, name: p.name, ig: p.instagram_business_account?.id })));

        // Find the first page that has an Instagram Business Account linked
        let igAccountId: string | null = null;
        let pageAccessToken: string | null = null;
        let linkedPageId: string | null = null;
        let fallbackPageName = pages[0]?.name || 'instagram_user';

        for (const page of pages) {
          if (page.instagram_business_account?.id) {
            igAccountId = page.instagram_business_account.id;
            pageAccessToken = page.access_token || null;
            linkedPageId = page.id;
            fallbackPageName = page.name;
            console.log(`[OAuth/Instagram] Found IG Business Account ${igAccountId} on page "${page.name}" (page_id: ${page.id})`);
            break;
          }
        }

        // If no page has IG Business Account, try querying each page individually
        // (fields=instagram_business_account sometimes omits it depending on app review status)
        if (!igAccountId) {
          for (const page of pages) {
            const pageToken = page.access_token || accessToken;
            const igRes = await fetch(
              `https://graph.facebook.com/v24.0/${page.id}?fields=instagram_business_account&access_token=${pageToken}`
            );
            const igData = await igRes.json();
            if (igData.instagram_business_account?.id) {
              igAccountId = igData.instagram_business_account.id;
              pageAccessToken = page.access_token || null;
              linkedPageId = page.id;
              fallbackPageName = page.name;
              console.log(`[OAuth/Instagram] Found IG Business Account ${igAccountId} on page "${page.name}" (individual query)`);
              break;
            }
          }
        }

        if (!igAccountId) {
          // Hard fail — storing the wrong ID causes Graph API error #100 "does not exist"
          console.error('[OAuth/Instagram] No Instagram Business Account found on any Page. User must (1) have a Business/Creator IG account, (2) link it to a FB Page they admin, (3) grant instagram_basic + instagram_content_publish.');
          throw new Error('Aucun compte Instagram Business trouvé. Vérifiez que votre compte IG est en mode Business/Creator et lié à une Page Facebook que vous administrez.');
        }
        if (!pageAccessToken) {
          console.error('[OAuth/Instagram] Found IG Business Account but no Page Access Token returned. Check pages_show_list scope.');
          throw new Error('Token de page Facebook manquant. Vérifiez les permissions pages_show_list et pages_read_engagement.');
        }

        accountId = igAccountId;          // IG Business Account ID (17841...)
        accessToken = pageAccessToken;    // Page Access Token (required by Graph API for IG publishing)
        console.log(`[OAuth/Instagram] Stored account_id=${accountId} with page_access_token from page ${linkedPageId}`);

        // Get IG username from the Instagram Business Account
        const igInfoRes = await fetch(
          `https://graph.facebook.com/v24.0/${accountId}?fields=username,name&access_token=${accessToken}`
        );
        const igInfo = await igInfoRes.json();
        accountName = igInfo.username || igInfo.name || fallbackPageName;
        console.log(`[OAuth/Instagram] IG username resolved: "${accountName}" (from account ${accountId})`);
  } else {
        // Facebook Page — we need the PAGE access token and PAGE ID to publish
        // The user-level token cannot post to Pages; we need a Page Access Token
        const pagesRes = await fetch(
              `https://graph.facebook.com/v24.0/me/accounts?fields=id,name,access_token&access_token=${accessToken}`
            );
        const pagesData = await pagesRes.json();
        const pages = pagesData.data || [];

        console.log(`[OAuth/Facebook] Found ${pages.length} Facebook Pages:`, pages.map((p: any) => ({ id: p.id, name: p.name })));

        if (pages.length > 0) {
          // Use the first page's credentials (most users have one page)
          const page = pages[0];
          if (!page.access_token) {
            console.error('[OAuth/Facebook] Page found but no Page Access Token returned. Check pages_show_list scope.');
            throw new Error('Token de page Facebook manquant. Vérifiez les permissions pages_show_list et pages_manage_posts.');
          }
          accountId = page.id;              // Page ID (not user ID!) — used as /{page_id}/videos target
          accountName = page.name || 'facebook_page';
          accessToken = page.access_token;  // Page Access Token — required to publish to a Page
          console.log(`[OAuth/Facebook] Using Page Access Token for page "${page.name}" (page_id: ${page.id})`);
        } else {
          // Hard fail — no Page means publishing is impossible
          console.error('[OAuth/Facebook] No Facebook Pages found on this account.');
          throw new Error('Aucune Page Facebook trouvée sur ce compte. Vous devez administrer au moins une Page Facebook pour publier.');
        }
  }

  const expiresAt = longTokenData.expires_in
      ? new Date(Date.now() + longTokenData.expires_in * 1000).toISOString()
        : new Date(Date.now() + 60 * 24 * 60 * 60 * 1000).toISOString(); // 60 days default

  return { accessToken, accountId, accountName, expiresAt };
}

async function exchangeTikTokToken(code: string) {
    const clientKey = process.env.TIKTOK_CLIENT_KEY;
    const clientSecret = process.env.TIKTOK_CLIENT_SECRET;
    const redirectUri = `${process.env.NEXTAUTH_URL || process.env.NEXT_PUBLIC_APP_URL}/api/social/callback/tiktok`;

  const tokenRes = await fetch('https://open.tiktokapis.com/v2/oauth/token/', {
        method: 'POST',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
        body: new URLSearchParams({
                client_key: clientKey || '',
                client_secret: clientSecret || '',
                code,
                grant_type: 'authorization_code',
                redirect_uri: redirectUri,
        }),
  });

  const tokenData = await tokenRes.json();

  if (tokenData.error) {
        throw new Error(tokenData.error_description || tokenData.error);
  }

  return {
        accessToken: tokenData.access_token,
        refreshToken: tokenData.refresh_token,
        accountId: tokenData.open_id,
        accountName: `tiktok_${tokenData.open_id?.slice(0, 8)}`,
        expiresAt: tokenData.expires_in
          ? new Date(Date.now() + tokenData.expires_in * 1000).toISOString()
                : undefined,
  };
}

async function exchangeYouTubeToken(code: string) {
    const clientId = process.env.YOUTUBE_CLIENT_ID || process.env.GOOGLE_CLIENT_ID;
    const clientSecret = process.env.YOUTUBE_CLIENT_SECRET || process.env.GOOGLE_CLIENT_SECRET;
    const redirectUri = `${process.env.NEXTAUTH_URL || process.env.NEXT_PUBLIC_APP_URL}/api/social/callback?platform=youtube`;

  const tokenRes = await fetch('https://oauth2.googleapis.com/token', {
        method: 'POST',
        headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
        body: new URLSearchParams({
                code,
                client_id: clientId || '',
                client_secret: clientSecret || '',
                redirect_uri: redirectUri,
                grant_type: 'authorization_code',
        }),
  });

  const tokenData = await tokenRes.json();

  if (tokenData.error) {
        throw new Error(tokenData.error_description || tokenData.error);
  }

  // Get channel inf
  const channelRes = await fetch(
        `https://www.googleapis.com/youtube/v3/channels?part=snippet&mine=true`,
    { headers: { Authorization: `Bearer ${tokenData.access_token}` } }
      );
    const channelData = await channelRes.json();
    const channel = channelData.items?.[0];

  return {
        accessToken: tokenData.access_token,
        refreshToken: tokenData.refresh_token,
        accountId: channel?.id || 'unknown',
        accountName: channel?.snippet?.title || 'youtube_user',
        expiresAt: tokenData.expires_in
          ? new Date(Date.now() + tokenData.expires_in * 1000).toISOString()
                : undefined,
  };
}
