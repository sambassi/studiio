import { NextRequest, NextResponse } from 'next/server';
import { toJsStringLiteral, escapeHtml } from '@/lib/social/html-escape';
import { verifyState } from '@/lib/social/oauth-state';
import { auth } from '@/lib/auth/config';
import { supabaseAdmin as supabase } from '@/lib/db/supabase';

// GET /api/social/callback?platform=xxx&code=xxx&state=xxx
// OAuth callback handler for all social platforms
export async function GET(req: NextRequest) {
    try {
          const { searchParams } = new URL(req.url);
          const platform = searchParams.get('platform');
          const code = searchParams.get('code');
          const state = searchParams.get('state');
          const error = searchParams.get('error');

      if (error) {
              return redirectWithMessage('error', `Connexion refusee: ${error}`);
      }

      if (!platform || !code) {
              return redirectWithMessage('error', 'Parametres manquants');
      }

      // Validation du `state` (protection CSRF).
      //
      // Le `userId` lu ici designe le compte Studiio auquel le compte social
      // va etre rattache. Il etait pris TEL QUEL dans un parametre d'URL :
      // appeler cette route avec `state=<id victime>:0:x` rattachait le compte
      // social de l'appelant au compte Studiio de la victime.
      //
      // On exige donc maintenant la signature posee par /api/social/connect.
      // Un `state` herite (3 segments, non signe) est refuse : l'accepter
      // laisserait la faille entiere, un attaquant n'ayant qu'a omettre la
      // signature. Seul un flux OAuth deja en vol au moment du deploiement
      // peut tomber sur ce refus — l'utilisateur relance « Connecter ».
      const verified = verifyState(state);
      if (!verified.valid || !verified.userId) {
              console.warn('[SOCIAL_CALLBACK] state refuse', { platform, reason: verified.reason });
              return redirectWithMessage('error', 'State invalide');
      }
      const userId = verified.userId;

      let tokenData: { accessToken: string; refreshToken?: string; accountId: string; accountName: string; expiresAt?: string };

      switch (platform) {
        case 'instagram':
        case 'facebook':
                  tokenData = await exchangeMetaToken(code, platform);
                  break;
        case 'tiktok':
                  tokenData = await exchangeTikTokToken(code);
                  break;
        case 'youtube':
                  tokenData = await exchangeYouTubeToken(code);
                  break;
        default:
                  return redirectWithMessage('error', `Plateforme non supportee: ${platform}`);
      }

      // Save to database.
      // Note : `userId` here comes from state (generated by /api/social/connect).
      // The auth fix (PR #167) may have shifted user.id values, so the state
      // may carry a stale id. Cross-check with the current session and try
      // the session id as a fallback if the state-userId insert fails on
      // foreign-key.
      const sessionForCallback = await auth();
      const sessionUserId = sessionForCallback?.user?.id;
      const candidates = [
        userId,
        ...(sessionUserId && sessionUserId !== userId ? [sessionUserId] : []),
      ];
      console.log('[SOCIAL_CALLBACK] save attempt', {
        platform,
        stateUserId: userId,
        sessionUserId: sessionUserId || null,
        candidatesCount: candidates.length,
      });

      const now = new Date().toISOString();
      let dbError: any = null;
      let savedWithUserId: string | null = null;
      for (const candidate of candidates) {
        const { error: err } = await supabase
          .from('social_accounts')
          .upsert(
            {
              user_id: candidate,
              platform,
              account_id: tokenData.accountId,
              account_name: tokenData.accountName,
              access_token: tokenData.accessToken,
              refresh_token: tokenData.refreshToken || null,
              expires_at: tokenData.expiresAt || null,
              connected: true,
              updated_at: now,
            },
            { onConflict: 'user_id,platform' },
          );
        if (!err) {
          dbError = null;
          savedWithUserId = candidate;
          break;
        }
        dbError = err;
        console.error('[SOCIAL_CALLBACK] upsert failed with user_id=' + candidate, {
          code: (err as any).code,
          message: (err as any).message,
          details: (err as any).details,
          hint: (err as any).hint,
        });
      }

      if (dbError) {
        const detail = `${(dbError as any).code || '?'} ${(dbError as any).message || ''}${(dbError as any).hint ? ' — hint: ' + (dbError as any).hint : ''}`.trim();
        return redirectWithMessage('error', `Erreur de sauvegarde: ${detail}`);
      }
      console.log('[SOCIAL_CALLBACK] saved successfully', { platform, savedWithUserId });

      return redirectWithMessage('success', `${platform} connecte avec succes!`);
    } catch (error: any) {
          const msg = error?.message || String(error) || 'Erreur inconnue';
          const stack = error?.stack ? error.stack.split('\n').slice(0, 3).join(' | ') : '';
          console.error('[SOCIAL_CALLBACK_ERROR]', { platform: req.nextUrl.searchParams.get('platform'), msg, stack });
          return redirectWithMessage('error', msg + (stack ? ' — ' + stack : ''));
    }
}

function redirectWithMessage(type: string, message: string): NextResponse {
    const isSuccess = type === 'success';
    // Deux contextes, deux echappements — les confondre est une XSS.
    //
    // L'ancien `replace(/'/g, "\\'")` ne tenait pas : un antislash final
    // (`...\`) devenait `...\'` et fermait la chaine JS, permettant d'injecter
    // du script. Or `message` transporte `error_description`, un parametre
    // d'URL entierement controle par l'appelant.
    const jsMessage = toJsStringLiteral(message);
    const safeMessage = escapeHtml(message);
    const html = isSuccess
      ? `<!DOCTYPE html><html><head><title>Connexion reussie</title></head><body style="font-family:sans-serif;padding:40px;text-align:center">
<script>
  if (window.opener) {
    window.opener.postMessage({ type: 'social-oauth-success', message: ${jsMessage} }, '*');
  }
  setTimeout(() => window.close(), 800);
</script>
<p>✓ ${safeMessage}</p>
<p style="color:#888">Cette fenetre va se fermer automatiquement.</p>
</body></html>`
      : `<!DOCTYPE html><html><head><title>Erreur de connexion</title></head><body style="font-family:sans-serif;padding:40px;max-width:600px;margin:auto">
<h2 style="color:#c00">Echec de la connexion</h2>
<p style="background:#fee;padding:16px;border-radius:8px;border:1px solid #fcc"><strong>Detail :</strong> ${safeMessage}</p>
<p style="color:#555">Copiez le message ci-dessus et renvoyez-le pour diagnostic.</p>
<button onclick="window.close()" style="padding:10px 20px;background:#333;color:#fff;border:0;border-radius:6px;cursor:pointer">Fermer</button>
<script>
  if (window.opener) {
    window.opener.postMessage({ type: 'social-oauth-error', message: ${jsMessage} }, '*');
  }
</script>
</body></html>`;
    return new NextResponse(html, {
      headers: { 'Content-Type': 'text/html; charset=utf-8', 'X-Content-Type-Options': 'nosniff' },
    });
}

